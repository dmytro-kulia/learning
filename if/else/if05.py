print ("Данная программа поможет в подсчёте оценки исходя из баллов.")
print ("Ниже введите кл-во баллов, а я посчитаю оценку.")
points = float(input("Введите кл-во баллов: "))
if points >= 90:
    print("Ваша оценка: 5")
elif points >= 75:
    print("Ваша оценка: 4")
elif points >= 50:
    print("Ваша оценка: 3")
elif points >= 0:
    print("Ваша оценка: 2")