print ("Пользователь вводит 3 стороны, программа говорит сущевствует ли такой треугольник.")
a = float(input("Введите певую сторону: "))
b = float(input("Введите вторую сторону: "))
c = float(input("Введите третью сторону: "))
if a < (b + c) and b < (a + c) and c < (a + b):
    print ("Такой треугольник сущевствуетю.")
else:
    print ("Такого треугольника не существует")